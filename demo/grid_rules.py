def overload_minutes(pct: float) -> float | None:
    """부하율(%)에서 트립까지 시간(분). 곡선 첫 점 미만이면 None(트립 안 함)."""
    c = RULES['overload']['trip_curve']
    if pct < c[0][0]: return None
    for (p0, t0), (p1, t1) in zip(c, c[1:]):
        if pct <= p1: return t0 + (t1 - t0) * (pct - p0) / (p1 - p0)
    return c[-1][1]
